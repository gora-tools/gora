"""Promotion PR service — GORA generates a deterministic promotion PR.

Loads the manifest, applies the domain promotion in memory, writes the promoted
manifest to a branch, and opens a pull request via the bounded GitHub adapter.
Idempotent and audited. GORA opens the PR; it never merges (ADR-013).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING, Protocol

from gora.adapters.github import GitHubError, PullRequest
from gora.audit.logger import AuditLogger
from gora.domain.release.manifest import ReleaseManifest

if TYPE_CHECKING:
    from pathlib import Path


class GitHubOps(Protocol):
    """The narrow adapter surface the promotion-PR workflow needs."""

    def get_ref_sha(self, branch: str) -> str: ...
    def create_branch(self, name: str, from_sha: str) -> None: ...
    def get_file_sha(self, path: str, branch: str) -> str | None: ...
    def commit_file(
        self, path: str, content: str, branch: str, message: str, *, sha: str | None = None
    ) -> str: ...
    def find_open_pull_request(self, head: str) -> PullRequest | None: ...
    def create_pull_request(self, head: str, base: str, title: str, body: str) -> PullRequest: ...


@dataclass(frozen=True)
class PromotionPRResult:
    """Outcome of an open-promotion-PR operation."""

    pull_request: PullRequest
    stage: str
    version: str
    digest: str
    image: str
    branch: str
    created: bool  # True if a new PR was opened; False if an existing one was reused


class PromotionPRService:
    """Sequences: load manifest -> promote -> commit to a branch -> open PR."""

    def __init__(
        self,
        adapter: GitHubOps,
        manifest_path: Path,
        *,
        audit: AuditLogger | None = None,
    ) -> None:
        self._adapter = adapter
        self._manifest_path = manifest_path
        self._audit = audit or AuditLogger()

    def open_promotion_pr(
        self,
        stage: str,
        *,
        base: str = "main",
        repo_manifest_path: str = "release-manifest.yaml",
    ) -> PromotionPRResult:
        manifest = ReleaseManifest.from_yaml(self._manifest_path)
        result = manifest.promote(stage)
        if not result.success or manifest.candidate is None:
            raise ValueError(result.error or "no active candidate to promote")

        version = manifest.candidate.version
        digest = manifest.candidate.digest
        new_yaml = manifest.to_yaml_str()
        # The idempotency key is (stage, version). Within a manifest a version maps to one
        # digest (ADR-003), so the key also fixes the digest the PR promotes (ADR-013).
        branch = f"gora/promote-{stage}-{version}"

        # Ensure the branch exists (idempotent).
        try:
            self._adapter.get_ref_sha(branch)
        except GitHubError:
            base_sha = self._adapter.get_ref_sha(base)
            self._adapter.create_branch(branch, base_sha)

        # Write the promoted manifest to the branch.
        file_sha = self._adapter.get_file_sha(repo_manifest_path, branch)
        self._adapter.commit_file(
            repo_manifest_path,
            new_yaml,
            branch,
            f"promote {version} to {stage}",
            sha=file_sha,
        )

        # Open the PR, or reuse an existing open one (idempotent).
        existing = self._adapter.find_open_pull_request(branch)
        if existing is not None:
            pr, created = existing, False
        else:
            pr = self._adapter.create_pull_request(
                head=branch,
                base=base,
                title=f"Promote {version} to {stage}",
                body=(
                    f"Promotion generated by GORA.\n\n"
                    f"- stage: `{stage}`\n- version: `{version}`\n- digest: `{digest}`\n"
                ),
            )
            created = True

        self._audit.record(
            "promotion_pr",
            stage=stage,
            version=version,
            digest=digest,
            branch=branch,
            pr=pr.number,
            created=created,
        )
        return PromotionPRResult(
            pull_request=pr,
            stage=stage,
            version=version,
            digest=digest,
            image=manifest.candidate.image,
            branch=branch,
            created=created,
        )
